// Loads the chosen skin (setting skin, see lib/skins.js) into the shell's
// theme as an extra stylesheet, and swaps it live when the setting or the
// skin's file changes. Main.loadTheme() carries extra stylesheets over to a
// new shell theme, so the skin survives theme changes too.

import Gio from 'gi://Gio';
import GLib from 'gi://GLib';
import St from 'gi://St';

import {DEFAULT_SKIN, loadSkin, skinCss, skinFile} from './skins.js';

const RELOAD_DELAY_MS = 300; // editors and pywal write files in several steps

export class SkinLoader {
    constructor(settings, extensionDir) {
        this._settings = settings;
        this._extensionDir = extensionDir;
        this._loaded = null; // Gio.File in the theme
        this._monitor = null;
        this._reloadId = 0;
        // Generated stylesheets, a new name each time so St parses afresh
        // (and none shared with a nested test shell).
        this._runDir = Gio.File.new_for_path(GLib.build_filenamev([GLib.get_user_runtime_dir(), 'nextkeybor']));

        settings.connectObject('changed::skin', () => this._apply(), this);
        this._apply();
    }

    destroy() {
        this._settings.disconnectObject(this);
        if (this._reloadId)
            GLib.source_remove(this._reloadId);
        this._reloadId = 0;
        this._unwatch();
        this._unload();
    }

    _theme() {
        return St.ThemeContext.get_for_stage(global.stage).get_theme();
    }

    _apply() {
        const id = this._settings.get_string('skin') || DEFAULT_SKIN;
        this._watch(id);
        let file = null;
        try {
            const skin = loadSkin(id, this._extensionDir);
            if (skin.kind === 'css') {
                file = skin.file;
            } else if (skin.kind === 'json') {
                GLib.mkdir_with_parents(this._runDir.get_path(), 0o700);
                file = this._runDir.get_child(`skin-${GLib.uuid_string_random()}.css`);
                file.replace_contents(new TextEncoder().encode(skinCss(skin)), null, false,
                    Gio.FileCreateFlags.REPLACE_DESTINATION, null);
            }
        } catch (e) {
            console.error(`NextKeyBor: could not load skin ${id}: ${e.message}`);
            return; // keep the skin that is showing
        }
        if (!file) {
            this._unload();
            return;
        }
        // Parse it in a theme of its own first: a CSS error then keeps the
        // skin that is showing.
        try {
            new St.Theme().load_stylesheet(file);
        } catch (e) {
            console.error(`NextKeyBor: skin ${id} has a CSS error: ${e.message}`);
            this._deleteGenerated(file);
            return;
        }
        this._unload();
        try {
            this._theme().load_stylesheet(file);
            this._loaded = file;
        } catch (e) {
            console.error(`NextKeyBor: could not load skin ${id}: ${e.message}`);
            this._deleteGenerated(file);
        }
    }

    _unload() {
        if (!this._loaded)
            return;
        this._theme().unload_stylesheet(this._loaded);
        this._deleteGenerated(this._loaded);
        this._loaded = null;
    }

    _deleteGenerated(file) {
        if (this._runDir.equal(file.get_parent()))
            file.delete_async(GLib.PRIORITY_DEFAULT, null, null);
    }

    // Reload when the skin file is edited (or regenerated by pywal or
    // matugen). The folder is watched, as tools often replace the file.
    _watch(id) {
        const file = skinFile(id, this._extensionDir);
        if (this._watched && file && this._watched.equal(file))
            return;
        this._unwatch();
        if (!file)
            return;
        // A folder that doesn't exist yet (~/.cache/wal before pywal's first
        // run) is still watched, and seen once it appears.
        try {
            this._monitor = file.get_parent().monitor_directory(Gio.FileMonitorFlags.WATCH_MOVES, null);
        } catch (e) {
            console.warn(`NextKeyBor: cannot watch ${file.get_path()}: ${e.message}`);
            return;
        }
        this._watched = file;
        this._monitor.connect('changed', (_m, changed, other) => {
            if (!file.equal(changed) && !(other && file.equal(other)))
                return;
            if (this._reloadId)
                GLib.source_remove(this._reloadId);
            this._reloadId = GLib.timeout_add(GLib.PRIORITY_DEFAULT, RELOAD_DELAY_MS, () => {
                this._reloadId = 0;
                this._apply();
                return GLib.SOURCE_REMOVE;
            });
        });
    }

    _unwatch() {
        this._monitor?.cancel();
        this._monitor = null;
        this._watched = null;
    }
}
